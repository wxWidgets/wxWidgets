bool TLWDragSession::Start(Seat& seat,
                           wxWindow* originTLW,
                           wxWindow* target,
                           wxWindow* targetTLW)
{
    wl_data_device* const device = seat.GetDataDevice();
    if ( !device )
        return false;

    // Note that the drag must originate from the surface having the implicit
    // grab, which is not necessarily the one we're going to drag over.
    GdkWindow* const gdkWindow = gtk_widget_get_window(originTLW->GetHandle());
    wl_surface* const surface = gdk_wayland_window_get_wl_surface(gdkWindow);
    if ( !surface )
        return false;

    m_source.reset(wl_data_device_manager_create_data_source(
        WLGlobals.data_device_manager.get()
    ));
    if ( !m_source )
        return false;

    wl_data_source_add_listener(m_source.get(), &data_source_listener, this);
    wl_data_source_offer(m_source.get(), TLW_DRAG_MIME_TYPE);
    wl_data_source_set_actions(m_source.get(),
                               WL_DATA_DEVICE_MANAGER_DND_ACTION_MOVE);

    // Note that the toplevel drag object must be created before starting the
    // drag using this source.
    m_drag.reset(xdg_toplevel_drag_manager_v1_get_xdg_toplevel_drag(
        WLGlobals.toplevel_drag_manager.get(), m_source.get()
    ));
    if ( !m_drag )
        return false;

    wl_data_device_start_drag(
        device,
        m_source.get(),
        surface,
        nullptr, // no drag icon
        seat.lastButtonSerial
    );

    m_target = target;
    m_tlw = targetTLW;

    // Make the TLW a drop target accepting our own private format for the
    // duration of the drag: this is the only way to be notified about the
    // pointer position, as we don't get any mouse events while the drag is in
    // progress, and it is also required for the drop to happen at all.
    //
    // Note that we use the TLW widget itself and not the widget used for the
    // drop targets set by the application, if any, so we don't conflict with
    // them: GTK looks for a suitable drop target up the widget hierarchy, so
    // this one is still found if none of the children accepts our format.
    m_targetWidget = targetTLW->GetHandle();
    g_object_ref(m_targetWidget);

    GtkTargetEntry entry = { const_cast<gchar*>(TLW_DRAG_MIME_TYPE), 0, 0 };
    gtk_drag_dest_set(
        m_targetWidget,
        GtkDestDefaults(0), // see comment in wxDropTarget::GtkRegisterWidget()
        &entry, 1,
        GdkDragAction(0)
    );

    g_signal_connect(m_targetWidget, "drag-motion",
                     G_CALLBACK(wx_tlw_drag_motion), this);
    g_signal_connect(m_targetWidget, "drag-leave",
                     G_CALLBACK(wx_tlw_drag_leave), this);
    g_signal_connect(m_targetWidget, "drag-drop",
                     G_CALLBACK(wx_tlw_drag_drop), this);

    wxLogTrace(TRACE_WAYLAND, "Started TLW drag from %s over %s",
               wxDumpWindow(originTLW), wxDumpWindow(target));

    return true;
}

bool TLWDragSession::AttachWindow(wxWindow* tlw, const wxPoint& offset)
{
    wxCHECK_MSG( m_drag, false, "drag must be running" );

    GtkWidget* const widget = tlw->GetHandle();
    GdkWindow* const window = widget ? gtk_widget_get_window(widget) : nullptr;
    if ( !window )
    {
        wxLogTrace(TRACE_WAYLAND, "No GdkWindow for the window to drag?");
        return false;
    }

    xdg_toplevel* const toplevel = gdk_wayland_window_get_xdg_toplevel(window);
    if ( !toplevel )
    {
        wxLogTrace(TRACE_WAYLAND, "No xdg_toplevel for the window to drag?");
        return false;
    }

    xdg_toplevel_drag_v1_attach(m_drag.get(), toplevel, offset.x, offset.y);

    return true;
}

void TLWDragSession::OnDragOver(int x, int y)
{
    // GTK may still notify us about the drop and the leaving of the window
    // after the data source has been told that the drop was performed.
    if ( m_ended )
        return;

    if ( !m_win )
    {
        m_win = m_target;

        wxLogTrace(TRACE_WAYLAND, "TLW drag entered %s", wxDumpWindow(m_win));
    }

    m_lastPos = GetScreenPos(m_tlw, x, y);

    NotifyDragOver();
}

void TLWDragSession::OnDragLeave()
{
    if ( m_ended )
        return;

    wxLogTrace(TRACE_WAYLAND, "TLW drag left %s", wxDumpWindow(m_win));

    m_win = nullptr;

    NotifyDragOver();
}

void TLWDragSession::OnDragEnd(TLWDragResult result)
{
    if ( m_ended )
        return;

    m_ended = true;

    // Don't notify the handler from here, as it is going to update the layout
    // and may well destroy the window being dragged -- and this object too --
    // which is better not done from inside a Wayland event handler.
    //
    // Use this shared pointer to ensure that we don't use this object if it is
    // destroyed before the notification is executed.
    auto alive = m_alive;

    // TODO-C++14: copy the values in the capture list itself.
    auto* const handler = m_handler.get();
    wxWindow* const win = m_win;
    const wxPoint pos = m_lastPos;

    wxTheApp->CallAfter([alive, handler, win, pos, result]() {
        if ( !*alive )
            return;

        switch ( result )
        {
            case TLWDragResult::Drop:
                handler->OnDragDrop(win, pos);
                break;

            case TLWDragResult::Cancel:
                handler->OnDragCancel();
                break;
        }
    });
}

