void
pointer_handle_enter(void* data,
                     wl_pointer* WXUNUSED(pointer),
                     uint32_t serial,
                     wl_surface* WXUNUSED(surface),
                     wl_fixed_t WXUNUSED(x),
                     wl_fixed_t WXUNUSED(y))
{
    auto* const seat = static_cast<Seat*>(data);

    seat->lastEnterSerial = serial;
}

void
pointer_handle_leave(void* data,
                     wl_pointer* WXUNUSED(pointer),
                     uint32_t WXUNUSED(serial),
                     wl_surface* WXUNUSED(surface))
{
    auto* const seat = static_cast<Seat*>(data);

    seat->lastEnterSerial = 0;
}

void
pointer_handle_motion(void* WXUNUSED(data),
                      wl_pointer* WXUNUSED(pointer),
                      uint32_t WXUNUSED(time),
                      wl_fixed_t WXUNUSED(x),
                      wl_fixed_t WXUNUSED(y))
{
}

void
pointer_handle_button(void* data,
                      wl_pointer* WXUNUSED(pointer),
                      uint32_t serial,
                      uint32_t WXUNUSED(time),
                      uint32_t WXUNUSED(button),
                      uint32_t state)
{
#ifdef wxHAVE_WAYLAND_TOPLEVEL_DRAG
    auto* const seat = static_cast<Seat*>(data);

    // We only need the serial of the last button press, as this is the one
    // identifying the implicit grab which we must refer to when starting a
    // drag, see TLWDragSession::Start().
    if ( state == WL_POINTER_BUTTON_STATE_PRESSED )
        seat->lastButtonSerial = serial;
#else // !wxHAVE_WAYLAND_TOPLEVEL_DRAG
    wxUnusedVar(data);
    wxUnusedVar(serial);
    wxUnusedVar(state);
#endif // wxHAVE_WAYLAND_TOPLEVEL_DRAG
}

void
pointer_handle_axis(void* WXUNUSED(data),
                    wl_pointer* WXUNUSED(pointer),
                    uint32_t WXUNUSED(time),
                    uint32_t WXUNUSED(axis),
                    wl_fixed_t WXUNUSED(value))
{
}

