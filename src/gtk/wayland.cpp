// We only need our own data device to be able to start the drag, but we still
// have to handle its events, if only to avoid leaking the data offer objects
// created for us, and they're also useful for debugging.

void
data_device_handle_data_offer(void* data,
                              wl_data_device* WXUNUSED(device),
                              wl_data_offer* offer)
{
    wxLogTrace(TRACE_WAYLAND, "Unexpected data offer on our own data device");

    // This also destroys the previous offer, which is not needed any longer.
    static_cast<Seat*>(data)->last_data_offer.reset(offer);
}

void
data_device_handle_enter(void* WXUNUSED(data),
                         wl_data_device* WXUNUSED(device),
                         uint32_t WXUNUSED(serial),
                         wl_surface* surface,
                         wl_fixed_t x,
                         wl_fixed_t y,
                         wl_data_offer* WXUNUSED(offer))
{
    wxWindow* const win = FindWindowForSurface(surface);

    wxLogTrace(TRACE_WAYLAND, "TLW drag entered %s at (%d, %d)",
               wxDumpWindow(win), wl_fixed_to_int(x), wl_fixed_to_int(y));

    // Note that we don't accept nor reject the offer here: this is done by GTK
    // for its own data device, see the drop target functions above.
}

void
data_device_handle_leave(void* data,
                         wl_data_device* WXUNUSED(device))
{
    wxLogTrace(TRACE_WAYLAND, "TLW drag left the window");

    static_cast<Seat*>(data)->last_data_offer.reset();
}

void
data_device_handle_motion(void* WXUNUSED(data),
                          wl_data_device* WXUNUSED(device),
                          uint32_t WXUNUSED(time),
                          wl_fixed_t WXUNUSED(x),
                          wl_fixed_t WXUNUSED(y))
{
}

void
data_device_handle_drop(void* data,
                        wl_data_device* WXUNUSED(device))
{
    wxLogTrace(TRACE_WAYLAND, "Unexpected drop on our own data device");

    static_cast<Seat*>(data)->last_data_offer.reset();
}

void
data_device_handle_selection(void* data,
                             wl_data_device* WXUNUSED(device),
                             wl_data_offer* WXUNUSED(offer))
{
    // We don't use this data device for the clipboard, GTK uses its own one
    // for it, so just get rid of the offer: note that this doesn't affect the
    // offer for the same selection received by the GTK data device.
    static_cast<Seat*>(data)->last_data_offer.reset();
}

const wl_data_device_listener data_device_listener = {
    data_device_handle_data_offer,
    data_device_handle_enter,
    data_device_handle_leave,
    data_device_handle_motion,
    data_device_handle_drop,
    data_device_handle_selection,
};

// ----------------------------------------------------------------------------
// wl_data_source listener: tells us when and how the drag ends
// ----------------------------------------------------------------------------

void
data_source_handle_target(void* WXUNUSED(data),
                          wl_data_source* WXUNUSED(source),
                          const char* mimeType)
{
    static wxString s_mimeType;

    // Filter out identical messages, there are too many of them otherwise.
    if ( !mimeType || s_mimeType.compare(mimeType) == 0 )
        return;

    s_mimeType = wxString::FromUTF8(mimeType);

    wxLogTrace(TRACE_WAYLAND, "TLW drag target now accepts \"%s\"", s_mimeType);
}

void
data_source_handle_send(void* WXUNUSED(data),
                        wl_data_source* WXUNUSED(source),
                        const char* WXUNUSED(mimeType),
                        int32_t fd)
{
    // We never transfer any data, but we still must close the file descriptor
    // we're given to avoid leaking it.
    close(fd);
}

void
data_source_handle_cancelled(void* data,
                             wl_data_source* WXUNUSED(source))
{
    wxLogTrace(TRACE_WAYLAND, "TLW drag cancelled");

    static_cast<TLWDragSession*>(data)->OnDragEnd(TLWDragResult::Cancel);
}

void
data_source_handle_dnd_drop_performed(void* data,
                                      wl_data_source* WXUNUSED(source))
{
    wxLogTrace(TRACE_WAYLAND, "TLW dropped");

    static_cast<TLWDragSession*>(data)->OnDragEnd(TLWDragResult::Drop);
}

void
data_source_handle_dnd_finished(void* WXUNUSED(data),
                                wl_data_source* WXUNUSED(source))
{
    wxLogTrace(TRACE_WAYLAND, "TLW drag finished");
}

void
data_source_handle_action(void* WXUNUSED(data),
                          wl_data_source* WXUNUSED(source),
                          uint32_t dndAction)
{
    wxLogTrace(TRACE_WAYLAND, "TLW drag action %#x", dndAction);
}

const wl_data_source_listener data_source_listener = {
    data_source_handle_target,
    data_source_handle_send,
    data_source_handle_cancelled,
    data_source_handle_dnd_drop_performed,
    data_source_handle_dnd_finished,
    data_source_handle_action,
};

