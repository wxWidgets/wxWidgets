// MIME type used by the drags started by TLWDragSession: we don't transfer any
// data at all, but a data source must offer something for the drop to be
// accepted and this also allows us to recognize our own drags.
constexpr const char* TLW_DRAG_MIME_TYPE = "application/x-wxwidgets-tlw-drag";

// Return the TLW using the given Wayland surface or null.
wxWindow* FindWindowForSurface(wl_surface* surface)
{
    for ( auto* const win : wxTopLevelWindows )
    {
        GtkWidget* const widget = win->GetHandle();
        if ( !widget )
            continue;

        GdkWindow* const gdkWindow = gtk_widget_get_window(widget);
        if ( !gdkWindow )
            continue;

        if ( gdk_wayland_window_get_wl_surface(gdkWindow) == surface )
            return win;
    }

    return nullptr;
}

// Convert surface-local coordinates inside the given TLW to wx screen ones.
//
// Note that the "screen" coordinates are not really global under Wayland, but
// they are consistent with those used by all the windows inside this TLW, and
// this is all we need.
wxPoint GetScreenPos(wxWindow* win, int x, int y)
{
    gint ox = 0,
         oy = 0;
    gdk_window_get_origin(gtk_widget_get_window(win->GetHandle()), &ox, &oy);

    return wxPoint(ox + x, oy + y);
}

// Used with TLWDragSession::OnDragEnd() to indicate how the drag ended.
enum class TLWDragResult
{
    // Dropped successfully.
    Drop,

    // Cancelld or dropped outside of any of our windows.
    Cancel
};

// The class implementing wxTLWDragSession under Wayland.
class TLWDragSession : public wxTLWDragSession
{
public:
    explicit TLWDragSession(std::unique_ptr<wxTLWDragHandler> handler)
        : m_handler(std::move(handler)),
          m_alive(std::make_shared<bool>(true))
    {
    }

    ~TLWDragSession()
    {
        *m_alive = false;

        if ( m_targetWidget )
        {
            g_signal_handlers_disconnect_by_data(m_targetWidget, this);
            gtk_drag_dest_unset(m_targetWidget);
            g_object_unref(m_targetWidget);
        }

        if ( !m_ended )
        {
            // Destroying these objects while the drag is still running is a
            // protocol error which would abort the program, so prefer to leak
            // them: this is not supposed to happen anyhow.
            wxLogTrace(TRACE_WAYLAND, "Drag is still running in ~TLWDragSession!");

            m_drag.release();
            m_source.release();
        }
    }

    // Actually start the drag from the given window, which must be inside the
    // given TLW.
    bool Start(Seat& seat,
               wxWindow* originTLW,
               wxWindow* target,
               wxWindow* targetTLW);

    bool AttachWindow(wxWindow* tlw, const wxPoint& offset) override;

    // Notifications from the GTK drop target signal handlers, the coordinates
    // here are relative to the TLW we're dragging over.
    void OnDragOver(int x, int y);
    void OnDragLeave();

    // Notification from the data source listener.
    void OnDragEnd(TLWDragResult result);

private:
    // Notify the handler about the current position.
    void NotifyDragOver()
    {
        m_handler->OnDragOver(m_win, m_lastPos);
    }

    const std::unique_ptr<wxTLWDragHandler> m_handler;

    // Flag used to avoid using this object from the delayed end notification
    // if it's destroyed before it is executed.
    const std::shared_ptr<bool> m_alive;

    wl_unique_ptr<wl_data_source> m_source;
    wl_unique_ptr<xdg_toplevel_drag_v1> m_drag;

    // The only window we report the drag position for and the TLW containing
    // it, whose coordinates are used for the conversions.
    wxWindow* m_target = nullptr;
    wxWindow* m_tlw = nullptr;

    // The widget which is temporarily made a drop target for the duration of
    // the drag, i.e. the GtkWindow of m_tlw. We hold a reference to it.
    GtkWidget* m_targetWidget = nullptr;

    // The origin window if the pointer is currently over it or null, and the
    // last position of the pointer in wx screen coordinates.
    wxWindow* m_win = nullptr;
    wxPoint m_lastPos;

    // Set once the drag is over, whether it ended with a drop or was cancelled.
    bool m_ended = false;
};

// ----------------------------------------------------------------------------
// GTK drop target: this is how we're notified about the drag progress
// ----------------------------------------------------------------------------

// Note that we can't use our own wl_data_device for this, even though we do
// create one in order to be able to start the drag, because the compositor may
// not send the drag events to it (KWin doesn't) and, even if it does, GTK would
// still refuse the drop using its own data device, resulting in the drag being
// cancelled instead of dropped. So we have to let GTK handle the drop side and
// simply make the window we're dragging over a drop target accepting our own
// private format for the duration of the drag.

// Check if the drag currently being handled is our own one, i.e. if it offers
// the private format used by TLW_DRAG_MIME_TYPE.
bool IsOurTLWDrag(GtkWidget* widget, GdkDragContext* context)
{
    return gtk_drag_dest_find_target(widget, context, nullptr) != GDK_NONE;
}

gboolean
wx_tlw_drag_motion(GtkWidget* widget,
                   GdkDragContext* context,
                   gint x,
                   gint y,
                   guint time,
                   TLWDragSession* session)
{
    if ( !IsOurTLWDrag(widget, context) )
        return FALSE;

    // Accepting the drag is required to get the drop when the mouse is
    // released, without it the drag would be simply cancelled.
    gdk_drag_status(context, GDK_ACTION_MOVE, time);

    session->OnDragOver(x, y);

    return TRUE;
}

void
wx_tlw_drag_leave(GtkWidget* WXUNUSED(widget),
                  GdkDragContext* WXUNUSED(context),
                  guint WXUNUSED(time),
                  TLWDragSession* session)
{
    session->OnDragLeave();
}

gboolean
wx_tlw_drag_drop(GtkWidget* widget,
                 GdkDragContext* context,
                 gint x,
                 gint y,
                 guint time,
                 TLWDragSession* session)
{
    if ( !IsOurTLWDrag(widget, context) )
        return FALSE;

    // Use the drop position as the final one.
    session->OnDragOver(x, y);

    // We don't have any data to retrieve, so we're done with the drop: this
    // also results in the data source being notified about it.
    gtk_drag_finish(context, TRUE /* success */, FALSE /* delete */, time);

    return TRUE;
}

