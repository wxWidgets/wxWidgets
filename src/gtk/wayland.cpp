// Use v2 of the wl_seat interface, as this is enough for our needs and frees
// us from providing empty implementations of the new pointer events introduced
// in v5.
constexpr uint32_t SEAT_VERSION = 2;

#ifdef wxHAVE_WAYLAND_TOPLEVEL_DRAG
// Use v3 of wl_data_device_manager interface required for the drag and drop
// actions support.
constexpr uint32_t DATA_DEVICE_MANAGER_VERSION = 3;
#endif // wxHAVE_WAYLAND_TOPLEVEL_DRAG

using SeatIds = std::vector<uint32_t>;

void
registry_handle_global(void* data,
                       wl_registry* registry,
                       uint32_t name,
                       const char* interface,
                       uint32_t version)
{
    if ( strcmp(interface, wl_seat_interface.name) == 0 )
    {
        if ( version < SEAT_VERSION )
        {
            wxLogTrace(TRACE_WAYLAND,
                       "Wayland seat interface v%u for seat %u is too old",
                       version, name);
            return;
        }

        static_cast<SeatIds*>(data)->push_back(name);
    }

    if ( strcmp(interface, wp_pointer_warp_v1_interface.name) == 0 )
    {
        WLGlobals.pointer_warp.reset(static_cast<wp_pointer_warp_v1*>(
            wl_registry_bind(registry, name, &wp_pointer_warp_v1_interface, 1)
        ));
    }

#ifdef wxHAVE_WAYLAND_TOPLEVEL_DRAG
    if ( strcmp(interface, wl_data_device_manager_interface.name) == 0 )
    {
        // We need v3 for wl_data_source_set_actions() and the drag and drop
        // actions in general, without which the drop is never accepted.
        if ( version < DATA_DEVICE_MANAGER_VERSION )
        {
            wxLogTrace(TRACE_WAYLAND,
                       "Wayland data device manager v%u is too old", version);
            return;
        }

        WLGlobals.data_device_manager.reset(static_cast<wl_data_device_manager*>(
            wl_registry_bind(registry, name, &wl_data_device_manager_interface,
                             DATA_DEVICE_MANAGER_VERSION)
        ));
    }

    if ( strcmp(interface, xdg_toplevel_drag_manager_v1_interface.name) == 0 )
    {
        // We can only use this protocol when this function is available, so
        // don't bother with it if it isn't.
        if ( gdk_wayland_window_get_xdg_toplevel )
        {
            WLGlobals.toplevel_drag_manager.reset(static_cast<xdg_toplevel_drag_manager_v1*>(
                wl_registry_bind(registry, name,
                                 &xdg_toplevel_drag_manager_v1_interface, 1)
            ));
        }
        else
        {
            wxLogTrace(TRACE_WAYLAND,
                       "Wayland toplevel drag manager is supported but GTK is too old to use it");
        }
    }
#endif // wxHAVE_WAYLAND_TOPLEVEL_DRAG

#ifdef wxHAVE_WAYLAND_SESSION_MANAGEMENT
    if ( strcmp(interface, xdg_session_manager_v1_interface.name) == 0 )
    {
        WLGlobals.session_manager.reset(static_cast<xdg_session_manager_v1*>(
            wl_registry_bind(registry, name, &xdg_session_manager_v1_interface, 1)
        ));
    }
#endif // wxHAVE_WAYLAND_SESSION_MANAGEMENT
}

void
registry_handle_global_remove(void* WXUNUSED(data),
                              wl_registry* WXUNUSED(registry),
                              uint32_t name)
{
    // Check if the global being removed is one of the seats.
    for ( auto it = WLGlobals.seats.begin();
          it != WLGlobals.seats.end();
          ++it )
    {
        if ( it->id == name )
        {
            WLGlobals.seats.erase(it);
            return;
        }
    }
}

const wl_registry_listener registry_listener = {
    registry_handle_global,
    registry_handle_global_remove
};

void Globals::Init()
{
    // Get the default Wayland display from GTK. If we ever want to support
    // more than one of them, we need to replace WLGlobals with per-display
    // objects.
    auto const manager = gdk_display_manager_get();
    auto const displayGDK = gdk_display_manager_get_default_display(manager);

    if ( !wxGTKImpl::IsWayland(displayGDK) )
        return;

    auto const displayWL = gdk_wayland_display_get_wl_display(displayGDK);

    // Get the registry and keep it alive in a member variable so that we keep
    // receiving the events about the globals being added and removed later.
    registry.reset(wl_display_get_registry(displayWL));

    // And get all of the current globals, storing the seat IDs in the provided
    // vector and pointer warp protocol directly in this global object itself.
    SeatIds seatIds;
    wl_registry_add_listener(registry.get(), &registry_listener, &seatIds);
    wl_display_roundtrip(displayWL);

    // Check if any of the protocols we may use are supported and, if none of
    // them are, just don't do anything at all.
    bool useAnyProtocol = false;

    if ( pointer_warp )
        useAnyProtocol = true;

#ifdef wxHAVE_WAYLAND_TOPLEVEL_DRAG
    // Note that the data device manager is always supported, but we still need
    // to check for it as we don't bind it unless we can use toplevel drags.
    if ( toplevel_drag_manager && data_device_manager )
        useAnyProtocol = true;
    else
        toplevel_drag_manager.reset();
#endif // wxHAVE_WAYLAND_TOPLEVEL_DRAG

    if ( !useAnyProtocol )
    {
        registry.reset();
        return;
    }

    // Otherwise initialize all seats, as we need to listen to "enter" and
    // "button" events on the pointer(s) associated with the seat(s).
    for ( auto name : seatIds )
    {
        auto const seat = static_cast<wl_seat*>(
            wl_registry_bind(registry.get(), name, &wl_seat_interface, SEAT_VERSION)
        );

        WLGlobals.seats.emplace_back(seat, name);
    }
}

void Globals::Free()
{
    registry.reset();

    // Note that the seats must be destroyed before the data device manager
    // used for creating the data devices owned by them.
    seats.clear();

    pointer_warp.reset();

#ifdef wxHAVE_WAYLAND_TOPLEVEL_DRAG
    toplevel_drag_manager.reset();

    data_device_manager.reset();
#endif // wxHAVE_WAYLAND_TOPLEVEL_DRAG
}

